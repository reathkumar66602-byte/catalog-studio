export type LocaleCode = (typeof LOCALES)[number]["code"];

export const DEFAULT_LOCALE: LocaleCode = "en";
export const LOCALE_STORAGE_KEY = "cs_locale";

const CODES = new Set<string>(LOCALES.map((item) => item.code));

export function isLocale(value: string | null | undefined): value is LocaleCode {
  return Boolean(value && CODES.has(value));
}

export function normalizeLocale(value: string | null | undefined): LocaleCode {
  if (!value) return DEFAULT_LOCALE;
  const code = value.trim().toLowerCase().replace("_", "-").split("-")[0];
  return isLocale(code) ? code : DEFAULT_LOCALE;
}

export function detectLocale(): LocaleCode {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (isLocale(stored)) return stored;
  const nav = window.navigator.language || "";
  return normalizeLocale(nav);
}

export function localeMeta(code: LocaleCode) {
  return LOCALES.find((item) => item.code === code) ?? LOCALES[0];
}

